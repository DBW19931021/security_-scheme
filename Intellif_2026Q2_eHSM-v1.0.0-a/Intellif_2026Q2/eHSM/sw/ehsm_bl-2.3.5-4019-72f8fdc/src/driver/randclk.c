#include "randclk.h"

/***********************************************************************************************************************
 *   VERSION CHECK
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  DEFINES & MACROS
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  EXTERN
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  LOCAL TYPEDEFS
 **********************************************************************************************************************/
typedef struct {
    uint32_t seed;
    uint32_t mode;
    uint32_t intp;
    uint32_t intp_en;
} randclk_reg_st;

/***********************************************************************************************************************
 *  LOCAL CONSTANTS
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  LOCAL VARIABLES
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  GLOBAL VARIABLES
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  LOCAL FUNCTION PROTOTYPES
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  LOCAL FUNCTION
 **********************************************************************************************************************/
static inline volatile randclk_reg_st *randclk_get_reg_base(void)
{
    return (volatile randclk_reg_st *)(RANDCLK_REG_BASE_ADDRESS);
}

/***********************************************************************************************************************
 *  GLOBAL FUNCTION
 **********************************************************************************************************************/
void randclk_start(uint32_t seed, uint32_t mode)
{
    volatile randclk_reg_st *randclk_reg = randclk_get_reg_base();
    randclk_reg->seed = seed;
    randclk_reg->mode = mode;
    randclk_reg->intp_en = 0U;
}

void randclk_stop(void)
{
    volatile randclk_reg_st *randclk_reg = randclk_get_reg_base();
    randclk_reg->mode = RANDCLK_MODE_NO_CLK_GATING;
}
