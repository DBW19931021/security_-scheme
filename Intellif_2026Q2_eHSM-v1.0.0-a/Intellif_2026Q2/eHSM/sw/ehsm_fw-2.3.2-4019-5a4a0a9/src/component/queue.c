static bool_t queue_is_empty(const queue_st *queue)
{
    bool_t ret;

    if (NULL == queue) {
        ret = true;
    } else if ((queue->front == queue->tail) && (!queue->full)) {
        ret = true;
    } else {
        ret = false;
    }
    return ret;
}

/***********************************************************************************************************************
 *  GLOBAL FUNCTION
 **********************************************************************************************************************/
uint32_t queue_init(queue_st *queue, queue_element_t *queue_elements, uint32_t elements_count)
{
    uint32_t ret;

    if ((NULL == queue) || (NULL == queue_elements) || (0U == elements_count)) {
        ret = EHSM_ERR_PARAM_ERROR;
    } else {
        queue->front = 0;
        queue->tail = 0;
        queue->full = false;
        queue->capacity = elements_count;
        queue->element_array = queue_elements;
        ret = EHSM_ERR_SW_SUCCESS;
    }

    return ret;
}

uint32_t queue_push(queue_st *queue, queue_element_t data)
{
    uint32_t ret;

    if ((NULL == queue) || (NULL == data)) {
        ret = EHSM_ERR_PARAM_ERROR;
    } else if (queue->full) {
        ret = EHSM_ERR_QUEUE_FULL;
    } else {
        queue->element_array[queue->tail] = data;
        if (queue->tail == 0U) {
            queue->tail = queue->capacity - 1U;
        } else {
            queue->tail--;
        }

        if (queue->tail == queue->front) {
            queue->full = true;
        }
        ret = EHSM_ERR_SW_SUCCESS;
    }

    return ret;
}

uint32_t queue_pop(queue_st *queue, queue_element_t *queue_data)
{
    uint32_t ret;

    if ((NULL == queue) || (NULL == queue_data)) {
        ret = EHSM_ERR_PARAM_ERROR;
    } else if (queue_is_empty(queue)) {
        ret = EHSM_ERR_QUEUE_EMPTY;
    } else {
        *queue_data = queue->element_array[queue->front];
        if (queue->front == 0U) {
            queue->front = queue->capacity - 1U;
        } else {
            queue->front--;
        }
        queue->full = false;
        ret = EHSM_ERR_SW_SUCCESS;
    }

    return ret;
}

bool_t queue_is_full(const queue_st *queue)
{
    bool_t ret;

    if (NULL == queue) {
        ret = false;
    } else {
        ret = queue->full;
    }
    return ret;
}

