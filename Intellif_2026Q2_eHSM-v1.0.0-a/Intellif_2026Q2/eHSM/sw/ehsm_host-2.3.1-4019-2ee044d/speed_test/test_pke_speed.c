static int test_ecdsa_single(speed_test_ctx_t *ctx, const char *key_type, bool is_generate)
{
    if (!ctx || !key_type)
        return -1;

    ehsm_port_printf("Testing ECDSA: %s, mode: %s\n", key_type, is_generate ? "generate" : "verify");

    // Determine key type ID
    uint32_t ecc_key_type;
    if (strcmp(key_type, "ECC_SECP_160K1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_SECP_160K1;
    } else if (strcmp(key_type, "ECC_SECP_160R1") == 0) {
        ehsm_port_printf("ECC_SECP_160R1 not supported, skipping\n");
        return 0;
    } else if (strcmp(key_type, "ECC_SECP_192K1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_SECP_192K1;
    } else if (strcmp(key_type, "ECC_SECP_192R1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_SECP_192R1;
    } else if (strcmp(key_type, "ECC_SECP_224K1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_SECP_224K1;
    } else if (strcmp(key_type, "ECC_SECP_224R1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_SECP_224R1;
    } else if (strcmp(key_type, "ECC_SECP_256K1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_SECP_256K1;
    } else if (strcmp(key_type, "ECC_SECP_256R1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_SECP_256R1;
    } else if (strcmp(key_type, "ECC_SECP_384R1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_SECP_384R1;
    } else if (strcmp(key_type, "ECC_SECP_521R1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_SECP_521R1;
    } else if (strcmp(key_type, "ECC_BP_256R1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_BRAINPOOLP_256R1;
    } else if (strcmp(key_type, "ECC_BP_384R1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_BRAINPOOLP_384R1;
    } else if (strcmp(key_type, "ECC_BP_512R1") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ECC_BRAINPOOLP_512R1;
    } else if (strcmp(key_type, "ED25519") == 0) {
        ecc_key_type = EHSM_KEY_TYPE_ED25519;
    } else {
        ehsm_port_printf("Unsupported ECC key type: %s\n", key_type);
        return -1;
    }

    // Generate ECC key
    uint32_t key_handle = 0x00100001;
    uint32_t ret = ehsm_km_gen_key(ctx->ehsm_ctx, ecc_key_type,
        EHSM_KEY_PRIV_SIGN | EHSM_KEY_PRIV_VERIFY | EHSM_KEY_PRIV_IMPORT_PLAIN, 0, 0, 0, 0, &key_handle);
    if (ret != EHSM_OK) {
        ehsm_port_printf("ECDSA key generation failed for %s: 0x%08x\n", key_type, ret);
        return -1;
    }

    uint32_t data_size = 32;       // SHA256 digest size
    uint32_t signature_size = 256; // Maximum ECDSA signature size buffer

    double total_time = 0.0;
    int success_count = 0;
    int loop_count = 1; // PKE operations are slower

    ehsm_hash_algo_e hash_algo;
    if (ecc_key_type == EHSM_KEY_TYPE_ED25519) {
        hash_algo = EHSM_HASH_ALGO_SHA512;
    } else {
        hash_algo = EHSM_HASH_ALGO_SHA256;
    }

    // Generate signature once for verification test
    if (!is_generate) {
        ret = ehsm_ecdsa_onepass_gen(ctx->ehsm_ctx, hash_algo, key_handle, ehsm_port_raddr_to_addr(ctx->data1_addr),
            data_size, ehsm_port_raddr_to_addr(ctx->data2_addr), &signature_size);
        if (ret != EHSM_OK) {
            ehsm_port_printf("ECDSA signature generation for verification test failed: 0x%08x\n", ret);
            return -1;
        }
    }

    for (int loop = 0; loop < loop_count; loop++) {
        double start = ehsm_port_get_time_ms();
        uint32_t sig_size = signature_size;

        if (is_generate) {
            ret = ehsm_ecdsa_onepass_gen(ctx->ehsm_ctx, hash_algo, key_handle, ehsm_port_raddr_to_addr(ctx->data1_addr),
                data_size, ehsm_port_raddr_to_addr(ctx->data2_addr), &sig_size);
        } else {
            bool_t verify_result;
            ret = ehsm_ecdsa_onepass_verify(ctx->ehsm_ctx, hash_algo, key_handle,
                ehsm_port_raddr_to_addr(ctx->data1_addr), data_size, ehsm_port_raddr_to_addr(ctx->data2_addr),
                signature_size, &verify_result);
            if (ret == EHSM_OK && !verify_result) {
                ret = 1; // Verification failed
            }
        }

        double end = ehsm_port_get_time_ms();
        double loop_time = end - start;

        if (ret == EHSM_OK && loop_time >= 0) {
            total_time += (loop_time > 0) ? loop_time : 1.0;
            success_count++;
        }
    }

    if (success_count == 0) {
        ehsm_port_printf("All test loops failed for %s %s\n", key_type, is_generate ? "gen" : "verify");
        return -1;
    }

    double avg_time = total_time / success_count;
    double speed_5m = calculate_speed_tps(avg_time);
    double speed_1g = speed_5m * 200.0;

    speed_test_result_t result = { 0 };
    strncpy(result.algo_name, key_type, sizeof(result.algo_name) - 1);
    strncpy(result.mode_name, is_generate ? "gen" : "verify", sizeof(result.mode_name) - 1);
    result.data_size = 0;
    result.is_encrypt = is_generate;
    result.loop_count = success_count;
    result.time_ms = avg_time;
    result.speed_5m_mbps = speed_5m;
    result.speed_1g_mbps = speed_1g;

    return speed_test_log_result(ctx, &result);
}

int test_pke_speed(speed_test_ctx_t *ctx)
{
    if (!ctx)
        return -1;

    ehsm_port_printf("\n=== Starting PKE Speed Tests ===\n");

    const char *rsa_key_types[] = { "RSA_1024", "RSA_1024_CRT", "RSA_2048", "RSA_2048_CRT", "RSA_3072", "RSA_3072_CRT",
        "RSA_4096", "RSA_4096_CRT" };

    const char *ecc_key_types[]
        = { "ECC_SECP_160K1", "ECC_SECP_160R1", "ECC_SECP_192K1", "ECC_SECP_192R1", "ECC_SECP_224K1", "ECC_SECP_224R1",
              "ECC_SECP_256K1", "ECC_SECP_256R1", "ECC_SECP_384R1", "ECC_SECP_521R1", "ED25519" };

    const size_t rsa_count = sizeof(rsa_key_types) / sizeof(rsa_key_types[0]);
    const size_t ecc_count = sizeof(ecc_key_types) / sizeof(ecc_key_types[0]);

    int total_tests = 0;
    int failed_tests = 0;

    for (size_t i = 0; i < rsa_count; i++) {
        total_tests += 2;

        if (test_rsa_single(ctx, rsa_key_types[i], true) != 0) {
            failed_tests++;
        }
        if (test_rsa_single(ctx, rsa_key_types[i], false) != 0) {
            failed_tests++;
        }
    }

    total_tests += 2;
    if (test_sm2_single(ctx, true) != 0) {
        failed_tests++;
    }
    if (test_sm2_single(ctx, false) != 0) {
        failed_tests++;
    }

    for (size_t i = 0; i < ecc_count; i++) {
        total_tests += 2;

        if (test_ecdsa_single(ctx, ecc_key_types[i], true) != 0) {
            failed_tests++;
        }
        if (test_ecdsa_single(ctx, ecc_key_types[i], false) != 0) {
            failed_tests++;
        }
    }

    ehsm_port_printf("PKE Speed Tests completed: %d total, %d failed\n", total_tests, failed_tests);
    return failed_tests == 0 ? 0 : -1;
}