//定义返回值错误码
enum SM2_RET_CODE
{
	SM2Success = 0, 
	SM2BufferNull,            // 空指针
	SM2InputLenInvalid,       // 输入长度非法，如长度为0等
	SM2PointHeadNot04,        // 公钥或曲线上点不以04开头
	SM2PubKeyError,           // 公钥错误
	SM2NotInCurve,            // 点不在曲线上
	SM2IntegerTooBig,         // 整数，如随机数K等过大
	SM2ZeroALL,               // 全0
	SM2DecryVerifyFailed,     // 解密校验失败
	SM2VerifyFailed,          // 签名验证失败
	SM2ExchangeRoleInvalid,   // 密钥交换用户角色无效
	SM2ZeroPoint,             // 0点，即无穷远点
	SM2InOutSameBuffer        // 输入输出同一个buffer
};

//SM2密钥交换用户角色
enum SM2_Exchange_Role
{
	SM2_Role_Receiver = 0,
	SM2_Role_Sender
};

