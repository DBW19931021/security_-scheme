/**
 * @brief 密钥交换的演示。
 *
 * @param[in] std_data 密钥交换的标准演示数据，详见 @ref demo_exchg_key_std_st
 *
 * @note
 * - 协商的时候，密钥协商的算法由 local_key_handle 所指向的 eHSM 内部本地私钥的密钥类型决定：
 *      - 若为 DH 密钥协商：
 *          - 需要指定 DH 公共参数，p，q，g 和他们的字节长度，其数据格式为：
 *              (p_len || p_value || q_len || q_value || g_len || g_value || h_len(可为 0) || h_value（可选）。
 *              p_len/q_len/g_len/h_len 均定为 4 字节，其值是对应的 p_value/q_value/g_value/h_value 的字节长度。
 *              h_value 指乘法加速的一个预计算数，是可选的，将 h_len 的值设置为 0 表示 h_value 不存在。除 h_len
 *              可以为 0 外，其他数据长度不能为 0，且必须是 4 字节的整数倍。
 *          - 指定协商的 key_size 最长为 DH 参数的 p 长度。
 *      - 若为 ECDH 密钥协商：
 *          - 协商的最大密钥长度为 512 字节。
 *          - 公钥为不含未压缩符号的点 x || y，例如 SECP256R1 的 ECDH 中，对端公钥为 64 字节， 即 (32B x || 32B y)。
 *      - 若为 SM2 密钥协商：
 *          - 协商的最大密钥长度为 512 字节。
 *          - 对端公钥、对端临时公钥均为 65 字节含未压缩符号 “0x04”，即 （0x04 || 32B x || 32B y）。
 *          - 需要指定额外的 SM2 参数，详见 @ref ehsm_sm2_params_st。
 * - 生成的 key handle 可以有两种选择：
 *      - Host 在 API 传参为有效的 key handle，具体参考固件 TRM 文档描述。
 *      - Host 在 API 传参为 0xFFFFFFFF，将由 eHSM 密钥管理服务分配 key handle。
 *
 */
static void demo_exchg_key(const demo_exchg_key_std_st *std_data)
{
    uint32_t ret = EHSM_OK;
    ehsm_ctx_st *ctx = ehsm_demo_get_ctx();         /* 用于 SoC API 存储 Mailbox 指令、返回值和配置的 buffer */
    uint8_t *peer_pubkey = ehsm_demo_get_buffer(0); /* 输入对端公钥的 buffer，必须是 SoC 和 eHSM 的共享内存 */
    uint32_t peer_pubkey_size;                      /* 用于指定对端公钥的字节长度 */
    uint8_t *dh_params = ehsm_demo_get_buffer(1);   /* 输入 DH 参数的 buffer，必须是 SoC 和 eHSM 的共享内存 */
    uint32_t dh_params_size;                        /* 用于 DH 参数的字节长度 */
    ehsm_sm2_params_st *sm2_params
        = (ehsm_sm2_params_st *)ehsm_demo_get_buffer(5); /* 输入 SM2 参数的 buffer，必须是 SoC 和 eHSM 的共享内存 */
    uint8_t *s1_s2
        = (uint8_t *)ehsm_demo_get_buffer(6); /* 输入 SM2 对端临时公钥的 buffer，必须是 SoC 和 eHSM 的共享内存 */
    uint8_t *sa_sb
        = (uint8_t *)ehsm_demo_get_buffer(7); /* 输入 SM2 对端临时公钥的 buffer，必须是 SoC 和 eHSM 的共享内存 */
    uint8_t *peer_temp_pubkey
        = (uint8_t *)ehsm_demo_get_buffer(8);   /* 输入 SM2 对端临时公钥的 buffer，必须是 SoC 和 eHSM 的共享内存 */
    uint32_t key_handle = std_data->key_handle; /* 用于指定密钥句柄，若为 0xFFFFFFFF 表示由 eHSM 分配 key handle */
    uint32_t local_key_handle = std_data->local_key_handle;         /* 用于指定本地私钥的密钥句柄 */
    uint32_t local_tmp_key_handle = std_data->local_tmp_key_handle; /* 用于指定本地临时私钥的密钥句柄 */
    bool_t generated_key_need_remove = false;                       /* 用于标记协商出来的密钥是否需要移除 */
    bool_t local_key_need_remove = false;                           /* 用于标记本地端密钥是否需要移除 */
    bool_t local_tmp_key_need_remove = false;                       /* 用于标记 SM2 本地端临时密钥是否需要移除 */

    ehsm_port_printf("[Demo starts.] \r\n");
    /* 打印标准数据信息 */
    ehsm_port_printf("%s. \r\n", std_data->desc);

    /* 拷贝数据至 SoC 和 eHSM 共享内存 */
    peer_pubkey_size = std_data->peer_pubkey_size;
    memcpy(peer_pubkey, std_data->peer_pubkey, peer_pubkey_size);
    print_hex("The peer public key is: \r\n    ", std_data->peer_pubkey, peer_pubkey_size);

    switch (std_data->local_key_type) {
    case EHSM_KEY_TYPE_DH:
        /* DH 算法需要 DH 公共参数 */
        dh_params_size = std_data->dh_params_size;
        memcpy(dh_params, std_data->dh_params, dh_params_size);
        print_hex("The dh common parameters is: \r\n    ", std_data->dh_params, dh_params_size);
        sm2_params = NULL;
        break;
    case EHSM_KEY_TYPE_ECC_SECP_256R1:
        dh_params = NULL;
        dh_params_size = 0U;
        sm2_params = NULL;
        break;
    case EHSM_KEY_TYPE_SM2:
        dh_params = NULL;
        dh_params_size = 0U;
        sm2_params->sm2_role = std_data->sm2_role;               /* SM2 的角色，本地端 sponsor，或者对端 responsor */
        sm2_params->local_tmp_key_handle = local_tmp_key_handle; /* 本地端临时密钥句柄，包含本地端临时私钥 */
        sm2_params->s1_s2_value_addr = ehsm_port_addr_to_raddr(s1_s2); /* 将 s1/s2 转换成 eHSM 可以识别的地址 */
        sm2_params->sa_sb_value_addr = ehsm_port_addr_to_raddr(sa_sb); /* 将 sa/sb 转换成 eHSM 可以识别的地址 */
        /* 拷贝对端临时公钥到 SoC 与 eHSM 共享内存 */
        memcpy(peer_temp_pubkey, std_data->peer_temp_pubkey, std_data->peer_temp_pubkey_size);
        sm2_params->peer_temp_pubkey_addr
            = ehsm_port_addr_to_raddr(peer_temp_pubkey); /* 将临时公钥转换成 eHSM 可以识别的地址 */
        sm2_params->peer_temp_pubkey_size = std_data->peer_temp_pubkey_size;
        print_hex("The peer temp public key is: \r\n    ", peer_temp_pubkey, sm2_params->peer_temp_pubkey_size);
        break;
    default:
        ret = 1;
        break;
    }

    /* 1. 所有 API 的调用都必须先初始化 ctx，指定 Mailbox 通道，配置同步/异步，异步模式的回调函数（可为空）。*/
    ehsm_ctx_init(ctx, 1, false, NULL);

    if (EHSM_OK == ret) {
        /* 2.1 生成一个本地密钥。 */
        ret = ehsm_km_gen_key(ctx, std_data->local_key_type,
            EHSM_KEY_PRIV_KEY_CREATION | EHSM_KEY_PRIV_IMPORT_PLAIN | EHSM_KEY_PRIV_REMOVE, 0U, 0U, dh_params,
            dh_params_size, &local_key_handle);
        ret = demo_check_val("The execution of generating key API:", EHSM_OK, ret);

        if (EHSM_OK == ret) {
            local_key_need_remove = true; /* 标记本地端密钥需要移除 */

            /* 检查返回的 local_key handle 是否和指定的值一致 */
            ret = demo_check_val(
                "Comparison for generated local key handle:", std_data->local_key_handle, local_key_handle);
        }
    }

    if (EHSM_OK == ret && EHSM_KEY_TYPE_SM2 == std_data->local_key_type) {
        /* 2.2 SM2 需要额外的本地临时私钥，这里直接生成一个。 */
        ret = ehsm_km_gen_key(ctx, std_data->local_key_type,
            EHSM_KEY_PRIV_KEY_CREATION | EHSM_KEY_PRIV_IMPORT_PLAIN | EHSM_KEY_PRIV_REMOVE, 0U, 0U, dh_params,
            dh_params_size, &local_tmp_key_handle);
        ret = demo_check_val("The execution of generating key API:", EHSM_OK, ret);

        if (EHSM_OK == ret) {
            local_tmp_key_need_remove = true; /* 标记 SM2 本地端临时密钥需要移除 */

            /* 检查返回的 local_key handle 是否和指定的值一致 */
            ret = demo_check_val("Comparison for generated local temp key handle:", std_data->local_tmp_key_handle,
                local_tmp_key_handle);
        }
    }

    if (EHSM_OK == ret) {
        /* 3. 调用密钥协商的 API。 */
        ret = ehsm_km_exchange_key(ctx, peer_pubkey, peer_pubkey_size, std_data->privilege, std_data->key_type,
            std_data->key_size, local_key_handle, dh_params, dh_params_size, sm2_params, &key_handle);
        ret = demo_check_val("The execution of key exchange API:", EHSM_OK, ret);

        if (EHSM_OK == ret) {
            generated_key_need_remove = true; /* 标记协商出来的密钥需要移除 */

            if (0xFFFFFFFF == std_data->key_handle) {
                /* 3. 若指定由 eHSM 分配，打印获取到的 key_handle */
                ehsm_port_printf("The key handle is: 0x%08x \r\n", key_handle);
            } else {
                /* 3. 若指定有效 key handle，则检查返回的 key handle 是否和指定的值一致 */
                ret = demo_check_val(
                    "Comparison for key handle generated by exchanging:", std_data->key_handle, key_handle);
            }
        }
    }

    if (generated_key_need_remove) {
        demo_remove_key(ctx, key_handle);
    }

    if (local_key_need_remove) {
        demo_remove_key(ctx, local_key_handle);
    }

    if (local_tmp_key_need_remove) {
        demo_remove_key(ctx, local_tmp_key_handle);
    }

    if (EHSM_OK == ret) {
        ehsm_port_printf("[Demo ends with success !!!] \r\n\r\n");
    } else {
        ehsm_port_printf("[Demo ends with failure. !!!] \r\n\r\n");
    }
}

/**
 * @brief 密钥协商的演示入口函数。
 */
void ehsm_demo_exchg_key_entry(void)
{
    uint32_t i;
    demo_exchg_key_std_st *std_data = s_exchg_key_std_data;
    uint32_t cnt = sizeof(s_exchg_key_std_data) / sizeof(demo_exchg_key_std_st);
    ehsm_port_printf("\r\n\r\n==================== eHSM demo for key exchange starts. "
                     "====================\r\n\r\n");

    for (i = 0U; i < cnt; i++) {
        ehsm_port_printf("demo for std_data[%d].\r\n", i);
        demo_exchg_key(&std_data[i]);
    }

    ehsm_port_printf("\r\n==================== eHSM demo for key exchange ends. ====================\r\n\r\n");
}

