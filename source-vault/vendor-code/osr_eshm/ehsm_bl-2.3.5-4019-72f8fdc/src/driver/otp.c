uint32_t otp_init(void)
{
    return EHSM_ERR_SW_SUCCESS;
}

uint32_t otp_read(uint32_t addr, uint8_t *data, uint32_t size)
{
    uint32_t ret;

    if ((data == NULL) || (size == 0U)) {
        ret = EHSM_ERR_PARAM_ERROR;
    } else if ((addr < OTP_BASE_ADDR) || (addr >= (OTP_BASE_ADDR + OTP_CHIP_SIZE))
        || (size > (OTP_BASE_ADDR + OTP_CHIP_SIZE - addr))) {
        ret = EHSM_ERR_PARAM_ERROR;
    } else {
        if (sysreg_is_osr_fpga()) {
            (void)util_memcpy(data, (uint8_t *)addr, size);
            if (!sysreg_is_osr_fpga()) {
                ret = EHSM_ERR_READ_DEV_FAIL;
            } else {
                ret = EHSM_ERR_SW_SUCCESS;
            }
        } else {
            (void)util_memcpy(data, (uint8_t *)addr, size);
            ret = EHSM_ERR_SW_SUCCESS;
        }
    }

    return ret;
}

uint32_t otp_write(uint32_t addr, const uint8_t *data, uint32_t size)
{
    uint32_t ret;

    if ((data == NULL) || (size == 0U)) {
        ret = EHSM_ERR_PARAM_ERROR;
    } else if ((addr < OTP_BASE_ADDR) || (addr >= (OTP_BASE_ADDR + OTP_CHIP_SIZE))
        || (size > (OTP_BASE_ADDR + OTP_CHIP_SIZE - addr))) {
        ret = EHSM_ERR_PARAM_ERROR;
    } else if (((addr % OTP_WRITE_UNIT) != 0U) || ((size % OTP_WRITE_UNIT) != 0U)) {
        ret = EHSM_ERR_NOT_ALIGNED;
    } else {
        if (sysreg_is_osr_fpga()) {
            (void)util_memcpy((uint8_t *)addr, data, size);
            if (!sysreg_is_osr_fpga()) {
                ret = EHSM_ERR_WRITE_DEV_FAIL;
            } else {
                ret = EHSM_ERR_SW_SUCCESS;
            }
        } else {
            // TODO: add your OTP driver
            ret = EHSM_ERR_NOT_SUPPORT;
        }
    }

    return ret;
}

