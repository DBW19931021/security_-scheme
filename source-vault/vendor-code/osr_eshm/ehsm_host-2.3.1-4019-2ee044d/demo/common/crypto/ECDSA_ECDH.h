//定义返回值错误码
enum ECDSA_ECDH_RET_CODE
{
	ECDSASuccess = 0, 
	ECDSABufferNull,            // 空指针
	ECDSAInputLenInvalid,       // 输入长度非法，如长度为0等
	ECDSAPointHeadNot04,        // 公钥或曲线上点不以04开头
	ECDSAPubKeyError,           // 公钥错误
	ECDSANotInCurve,            // 点不在曲线上
	ECDSAIntegerTooBig,         // 整数，如随机数K等过大
	ECDSAZeroALL,               // 全0
	ECDSADecryVerifyFailed,     // 解密校验失败
	ECDSAVerifyFailed,          // 签名验证失败
	ECDSAExchangeRoleInvalid,   // 密钥交换用户角色无效
	ECDSAZeroPoint,             // 0点，即无穷远点
	ECDSAInOutSameBuffer,       // 输入输出同一个buffer
	ECDSA_NINV_NOT_EXIST        // 输入输出同一个buffer
};

