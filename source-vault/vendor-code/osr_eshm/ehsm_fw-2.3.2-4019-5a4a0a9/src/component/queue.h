#ifndef EHSM_QUEUE_H
#define EHSM_QUEUE_H

/***********************************************************************************************************************
 *  INCLUDES
 **********************************************************************************************************************/
#include "types.h"

/***********************************************************************************************************************
 *   VERSION CHECK
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  DEFINES & MACROS
 **********************************************************************************************************************/
/***********************************************************************************************************************
 *  TYPEDEFS
 **********************************************************************************************************************/
typedef void *queue_element_t;

typedef struct {
    uint32_t front;
    uint32_t tail;
    uint32_t capacity;
    bool_t full;
    queue_element_t *element_array;
} queue_st;

/***********************************************************************************************************************
 *  CONSTANTS
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  GLOBAL VARIABLES
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  GLOBAL FUNCTION
 **********************************************************************************************************************/
uint32_t queue_init(queue_st *queue, queue_element_t *queue_elements, uint32_t elements_count);

uint32_t queue_push(queue_st *queue, queue_element_t data);

uint32_t queue_pop(queue_st *queue, queue_element_t *queue_data);

bool_t queue_is_full(const queue_st *queue);

#endif // EHSM_QUEUE_H
