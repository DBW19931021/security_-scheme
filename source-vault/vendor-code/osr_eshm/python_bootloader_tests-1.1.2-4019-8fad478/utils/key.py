# 测试接口封装：遵循密钥导入API要求的数据格式打包 KEY_HEAD + KEY_DATA
def pack_key_with_head(
    key_data: bytes,
    key_permit: KeyPermit,
    key_type: EhsmKeyType,
    key_part: EhsmKeyPart,
    pub_key_size: int,
    priv_key_size: int
) -> bytes:
    # key_data_head:ehsm_key_format_st
    key_head = struct.pack("<LBBHHH", key_permit, key_type, key_part, 0, pub_key_size, priv_key_size)
    log.debug(f"key_head: size: {len(key_head)}, data: {''.join(f'{b:02x}' for b in key_head) or '(empty)'}")
    pack_key = key_head + key_data
    log.debug(f"pack_key: size: {len(pack_key)}, data: {''.join(f'{b:02x}' for b in pack_key) or '(empty)'}")
    return pack_key


def pack_rsa_key_for_ex_api(
    n: bytes,
    e: bytes,
    d: bytes = b'',
    p: bytes = b'',
    q: bytes = b'',
    dp: bytes = b'',
    dq: bytes = b'',
    u: bytes = b'',
    base_addr: int = 0,
    crt_mode: int = None
) -> bytes:
    """
    将RSA密钥打包成 ehsm_rsa_key_st 结构格式,用于 *_ex 接口

    Args:
        n: RSA模数
        e: RSA公钥指数
        d: RSA私钥指数 (NO_CRT模式使用)
        p, q, dp, dq, u: CRT模式参数
        base_addr: 结构体写入的基地址 (默认0,会在实际使用时确定)
        crt_mode: CRT模式标志 (0=NO_CRT, 1=CRT), 如果为None则自动判断

    Returns:
        打包后的字节数据,包含 ehsm_rsa_key_st 结构和实际密钥数据

    C结构定义:
        typedef struct {
            uint8_t crt_mode;     // [offset: 0] 1=CRT模式, 0=NO_CRT模式
            uint8_t reserved0[3]; // [offset: 1-3] 保留
            uint32_t n_byte_sz;   // [offset: 4-7] n的字节数
            uint32_t e_byte_sz;   // [offset: 8-11] e的字节数
            raddr_t n;            // [offset: 12-19] n的地址 (8字节)
            raddr_t e;            // [offset: 20-27] e的地址
            raddr_t d;            // [offset: 28-35] d的地址
            raddr_t p;            // [offset: 36-43] p的地址
            raddr_t q;            // [offset: 44-51] q的地址
            raddr_t dp;           // [offset: 52-59] dp的地址
            raddr_t dq;           // [offset: 60-67] dq的地址
            raddr_t u;            // [offset: 68-75] u的地址
        } ehsm_rsa_key_st;  // 总共76字节
    """
    # Reason: CRT模式由外部参数提供,如果未提供则根据p和q自动判断
    if crt_mode is None:
        crt_mode = 1 if (p and q) else 0

    # Reason: 密钥对齐 - 所有私钥组件应该与n的长度一致,不足的前面补0
    n_len = len(n)

    # Reason: CRT模式下不使用d密钥,只使用CRT参数(p, q, dp, dq, u)
    if crt_mode:
        d = b''  # CRT模式下强制清空d
        log.debug(f"CRT模式: 忽略d参数")

    # 对齐 d (如果存在且不为空,且非CRT模式)
    if d and len(d) < n_len:
        d = b'\x00' * (n_len - len(d)) + d
        log.debug(f"对齐 d: 原长度 -> 新长度={len(d)}")

    # 对齐 CRT 参数 (如果使用CRT模式)
    if crt_mode:
        # p 和 q 的长度应该是 n_len/2
        half_n_len = n_len // 2

        if p and len(p) < half_n_len:
            p = b'\x00' * (half_n_len - len(p)) + p
            log.debug(f"对齐 p: 新长度={len(p)}")

        if q and len(q) < half_n_len:
            q = b'\x00' * (half_n_len - len(q)) + q
            log.debug(f"对齐 q: 新长度={len(q)}")

        if dp and len(dp) < half_n_len:
            dp = b'\x00' * (half_n_len - len(dp)) + dp
            log.debug(f"对齐 dp: 新长度={len(dp)}")

        if dq and len(dq) < half_n_len:
            dq = b'\x00' * (half_n_len - len(dq)) + dq
            log.debug(f"对齐 dq: 新长度={len(dq)}")

        if u and len(u) < half_n_len:
            u = b'\x00' * (half_n_len - len(u)) + u
            log.debug(f"对齐 u: 新长度={len(u)}")

    # Reason: 计算结构体后的数据偏移量
    # 结构体大小是76字节,数据从第76字节开始
    struct_size = 76
    data_offset = struct_size

    # Reason: 构建密钥数据部分,并计算每个组件的地址
    key_components_data = b''
    current_offset = base_addr + data_offset

    # 添加 n
    n_addr = current_offset
    key_components_data += n
    current_offset += len(n)

    # 添加 e
    e_addr = current_offset
    key_components_data += e
    current_offset += len(e)

    # 添加 d (如果存在)
    if d:
        d_addr = current_offset
        key_components_data += d
        current_offset += len(d)
    else:
        d_addr = 0

    # 添加 CRT 参数 (如果使用CRT模式)
    if crt_mode:
        p_addr = current_offset
        key_components_data += p
        current_offset += len(p)

        q_addr = current_offset
        key_components_data += q
        current_offset += len(q)

        dp_addr = current_offset
        key_components_data += dp
        current_offset += len(dp)

        dq_addr = current_offset
        key_components_data += dq
        current_offset += len(dq)

        u_addr = current_offset
        key_components_data += u
        current_offset += len(u)
    else:
        p_addr = q_addr = dp_addr = dq_addr = u_addr = 0

    # Reason: 打包 ehsm_rsa_key_st 结构
    # 格式: B(crt_mode) + 3x(reserved) + L(n_byte_sz) + L(e_byte_sz) + 8xQ(8个地址)
    rsa_key_struct = struct.pack(
        "<BBBBLLQQQQQQQQ",
        crt_mode,        # uint8_t crt_mode
        0, 0, 0,         # uint8_t reserved0[3]
        len(n),          # uint32_t n_byte_sz
        len(e),          # uint32_t e_byte_sz
        n_addr,          # raddr_t n
        e_addr,          # raddr_t e
        d_addr,          # raddr_t d
        p_addr,          # raddr_t p
        q_addr,          # raddr_t q
        dp_addr,         # raddr_t dp
        dq_addr,         # raddr_t dq
        u_addr           # raddr_t u
    )

    # Reason: 组合结构体和实际数据
    packed_key = rsa_key_struct + key_components_data

    log.debug(f"RSA密钥打包: CRT模式={crt_mode}, 结构体大小={len(rsa_key_struct)}, "
              f"数据大小={len(key_components_data)}, 总大小={len(packed_key)}")
    log.debug(f"  n_size={len(n)}, e_size={len(e)}, d_size={len(d)}")
    if crt_mode:
        log.debug(f"  CRT: p_size={len(p)}, q_size={len(q)}, dp_size={len(dp)}, "
                  f"dq_size={len(dq)}, u_size={len(u)}")

    return packed_key


def pack_ecc_key_for_ex_api(
    curve_id: int,
    private_key: bytes = b'',
    public_key: bytes = b'',
    base_addr: int = 0
) -> bytes:
    """
    将ECC密钥打包成 mb_ecc_key_st 结构格式,用于 *_ex 接口

    Args:
        curve_id: ECC曲线ID (来自 EhsmKeyType 枚举)
        private_key: ECC私钥 (原始字节,长度由curve_id决定)
        public_key: ECC公钥 (原始字节,不含0x04头部,长度由curve_id决定)
        base_addr: 结构体写入的基地址 (默认0,会在实际使用时确定)

    Returns:
        打包后的字节数据,包含 mb_ecc_key_st 结构和实际密钥数据

    C结构定义:
        typedef struct {
            uint32_t curve_id;  // [offset: 0] ECC曲线编号
            raddr_t privkey;    // [offset: 4] ECC私钥的存储地址的地址 (8字节)
            raddr_t pubkey;     // [offset: 12] ECC公钥的存储地址的地址 (8字节)
        } mb_ecc_key_st;  // 总共20字节

    注意:
        - 公钥应该是纯坐标数据,不包含 0x04 前缀
        - cryptosynth 返回的公钥包含 0x04,需要调用者去掉
    """
    # Reason: 如果公钥以 0x04 开头,去掉第一个字节(未压缩点标识)
    if public_key and len(public_key) > 0 and public_key[0] == 0x04:
        public_key = public_key[1:]
        log.debug(f"去除公钥 0x04 前缀,新长度: {len(public_key)}")

    # Reason: 根据 curve_id 确定私钥大小 (用于验签时填充全0私钥)
    ecc_privkey_sizes = {
        0x12: 20, 0x13: 24, 0x14: 28, 0x15: 32,  # Brainpool
        0x16: 40, 0x17: 48, 0x18: 64,             # Brainpool
        0x19: 24, 0x1a: 28, 0x1b: 32, 0x1c: 48, 0x1d: 66,  # SECP
        0x26: 20, 0x27: 24, 0x28: 28, 0x29: 32,  # 其他
    }
    expected_privkey_size = ecc_privkey_sizes.get(curve_id, 32)  # 默认P-256

    # Reason: 计算结构体后的数据偏移量
    # 结构体大小是20字节,数据从第20字节开始
    struct_size = 20
    data_offset = struct_size

    # Reason: 构建密钥数据部分,并计算每个组件的地址
    key_components_data = b''
    current_offset = base_addr + data_offset

    # Reason: 添加私钥 - 如果没有提供私钥但有公钥,则填充全0私钥(验签需要)
    if private_key:
        privkey_addr = current_offset
        key_components_data += private_key
        current_offset += len(private_key)
    elif public_key:
        # Reason: 验签时需要有效的私钥地址,但数据全为0
        privkey_addr = current_offset
        key_components_data += b'\x00' * expected_privkey_size
        current_offset += expected_privkey_size
    else:
        privkey_addr = 0

    # 添加公钥 (如果存在)
    if public_key:
        pubkey_addr = current_offset
        key_components_data += public_key
        current_offset += len(public_key)
    else:
        pubkey_addr = 0

    # Reason: 打包 mb_ecc_key_st 结构
    # 格式: L(curve_id) + Q(privkey_addr) + Q(pubkey_addr)
    ecc_key_struct = struct.pack(
        "<LQQ",
        curve_id,        # uint32_t curve_id
        privkey_addr,    # raddr_t privkey
        pubkey_addr      # raddr_t pubkey
    )

    # Reason: 组合结构体和实际数据
    packed_key = ecc_key_struct + key_components_data

    log.debug(f"ECC密钥打包: curve_id=0x{curve_id:02x}, 结构体大小={len(ecc_key_struct)}, "
              f"数据大小={len(key_components_data)}, 总大小={len(packed_key)}")
    log.debug(f"  privkey_size={len(private_key)}, pubkey_size={len(public_key)}")

    return packed_key
