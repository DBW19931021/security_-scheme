#ifndef UART_H
#define UART_H

/***********************************************************************************************************************
 *  INCLUDES
 **********************************************************************************************************************/
#include "types.h"

/***********************************************************************************************************************
 *   VERSION CHECK
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  DEFINES & MACROS
 **********************************************************************************************************************/
typedef void (*uart_recv_cb)(void);

// uart base register address
#define UART_BASE_ADDR 0x3F400000UL

// offset of uart data register address
#define UART_DATA 0x0

// offset of uart statu register address
#define UART_STATUS 0x4

// offset of uart control register address
#define UART_CTRL 0x8

// offset of uart interrupt status register address
#define UART_INT_STA 0xc

// offset of uart baud rate configuration register address
#define UART_BAUD_DIV 0x10

/***********************************************************************************************************************
 *  TYPEDEFS
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  CONSTANTS
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  GLOBAL VARIABLES
 **********************************************************************************************************************/

/***********************************************************************************************************************
 *  GLOBAL FUNCTION
 **********************************************************************************************************************/
uint32_t uart_init(uart_recv_cb cb, uint32_t baudrate_div);

void uart_putc(uint8_t c);

uint8_t uart_getc(void);

void uart_set_baudrate(uint32_t baudrate_div);

void uart_flush(void);

void uart_deinit(void);
#endif
